#!/usr/bin/env python3
"""Read-only consistency checks for documented commands vs the ACTUAL repository."""
import json
from pathlib import Path
import re
import sys

ROOT=Path(__file__).resolve().parents[1]
errors=[]
def expect(condition,reason):
 if not condition:errors.append(reason)
def read(path):return (ROOT/path).read_text(encoding="utf-8")
pkg=json.loads(read("package.json"))
root_scripts=pkg.get("scripts",{})
web=ROOT/"apps/web/package.json"
if web.exists():
 web_pkg=json.loads(web.read_text(encoding="utf-8"))
 expect(isinstance(pkg.get("workspaces"),list),"Migrated root must have npm workspaces.")
 expect((ROOT/"apps/web/app/page.tsx").is_file(),"Migrated Next app must contain apps/web/app/page.tsx.")
 expect(not (ROOT/"app/page.tsx").exists(),"Root app/page.tsx must have moved to apps/web.")
 expect(web_pkg.get("dependencies",{}).get("next"),"Web workspace missing Next.js dependency.")
 expect("lint" in web_pkg.get("scripts",{}),"Web workspace missing lint script.")
else:
 expect((ROOT/"app/page.tsx").is_file(),"Initial root Next.js app missing before P01.")
 expect(pkg.get("dependencies",{}).get("next")=="16.4.3","Existing Next version changed without an updated migration plan.")
 expect(pkg.get("dependencies",{}).get("react")=="19.3.0","Existing React version changed without an updated migration plan.")
 for name in ("dev","lint","build"):
  expect(name in root_scripts,"README says npm run "+name+" exists but package.json has no script.")
 expect(not pkg.get("workspaces"),"Workspaces configured but apps/web package not created: incomplete migration.")
expect((ROOT/"package-lock.json").is_file(),"npm root package-lock.json missing.")
expect(not (ROOT/"pnpm-lock.yaml").exists(),"pnpm lockfile conflicts with documented npm-only policy.")
agents=read("AGENTS.md")
expect("<!-- BEGIN:nextjs-agent-rules -->" in agents and "<!-- END:nextjs-agent-rules -->" in agents,
       "Autogenerated Next.js instructions missing from root AGENTS.md.")
expect("CODING AGENT" in agents,"Root AGENTS.md audience unclear.")
guide=read("PANDUAN-MULAI-LOW-AGENT.md")
expect("USER" in guide and "START-AGENT-PROMPT.md" in guide,"User guide entrypoint missing.")
for p in ("docs/agent/START-AGENT-PROMPT.md","docs/agent/RESUME-SESSION-PROMPT.md",
          "docs/agent/LOW-REASONING-RUNBOOK.md","docs/agent/TEST-AND-REVIEW-POLICY.md",
          "tools/agent_tasks.py","tools/split_agent_task.py","tools/validate_plan.py"):
 expect((ROOT/p).is_file(),"Referenced agent tool/document missing: "+p)
expect((ROOT/"tools/bootstrap_agent.py").is_file(),"Missing shell-independent agent bootstrap.")
expect("python3 tools/bootstrap_agent.py" in agents,"AGENTS.md must require automatic bootstrap.")
expect("python3 tools/bootstrap_agent.py" in read("docs/agent/START-AGENT-PROMPT.md"),"START prompt must bootstrap agent before tasks.")
expect("python3 tools/bootstrap_agent.py" in read("docs/agent/RESUME-SESSION-PROMPT.md"),"RESUME prompt must bootstrap agent before tasks.")
expect("source .venv-agent/bin/activate" not in read("docs/agent/START-AGENT-PROMPT.md"),"START prompt must not require POSIX activation.")
expect("Node.js 26" in agents and "npm/npx" in agents,"Runtime/package-manager instruction mismatch.")
# Check obvious root README claims against actual package scripts (not future P16 CLI placeholders).
readme=read("README.md")
if not web.exists():
 for cmd in re.findall(r"npm run ([a-z][a-z0-9:-]+)",readme):
  expect(cmd in root_scripts,"README references unavailable current npm script: "+cmd)
if errors:
 for error in errors:print("ERROR:",error)
 sys.exit(1)
print("OK: actual Next/npm baseline, user/agent entrypoints, and referenced tools agree.")
print("This check is read-only and does not prove application functions are implemented.")
